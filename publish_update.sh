#!/bin/bash
set -e

DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
cd "$DIR"

MSG="${1:-Автоматичне оновлення дизайну та функціоналу OrderDesk}"

echo "========================================================"
echo "🚀 Публікація оновлення OrderDesk у хмару (GitHub)"
echo "Коміт: $MSG"
echo "========================================================"

# 1. Додаємо файли проекту до git
git add -A

# 2. Робимо коміт
if git diff-index --quiet HEAD --; then
    echo "[OrderDesk] Немає нових змін для коміту."
else
    git commit -m "$MSG"
fi

# 3. Відправляємо на GitHub
echo "[OrderDesk] Відправка оновлення на GitHub..."
git push origin main

# 4. Оновлюємо архів клієнта на Mac з новим version_commit.txt
./package_for_clients.sh

echo "========================================================"
echo "✓ Успішно! Оновлення опубліковано на GitHub."
echo "Тепер на другому ПК воно підтягнеться САМО при запуску"
echo "або через кнопку оновлення в інтерфейсі!"
echo "========================================================"
