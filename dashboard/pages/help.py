def build_html() -> str:
    parts = [f'<body style="color:{theme.TEXT}; font-size:{theme.FONT_PX}px;">']
    parts.append(f'<h2 style="color:{theme.TEXT}">Як користуватись OrderDesk</h2>'
                 f'<p style="color:{theme.MUTED}">Короткий посібник від першого входу до дня продажу.</p>')
    for title, blocks in SECTIONS:
        parts.append(f'<h3 style="color:{theme.ACCENT}; margin-top:22px">{title}</h3>')
        for block in blocks:
            parts.append(f'<div style="color:{theme.TEXT}; line-height:150%">{block}</div>')
    parts.append("</body>")
    html = "".join(parts)
    for name in ("blue", "violet", "green", "amber", "red"):
        html = html.replace(f"@{name}", getattr(theme, name.upper()))
    return html


class HelpPage(Page):
    def __init__(self, parent=None):
        super().__init__("Інструкція", "Як налаштувати і користуватися програмою", parent)
        self.view = QTextBrowser()
        self.view.setObjectName("logView")
        self.view.setOpenExternalLinks(True)
        self.body.addWidget(self.view)
        self.refresh()

    def refresh(self) -> None:
        bar = self.view.verticalScrollBar()
        pos = bar.value()
        self.view.setHtml(build_html())
        bar.setValue(pos)
