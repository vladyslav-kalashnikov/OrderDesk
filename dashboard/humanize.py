_LEVEL_ICON = {"INFO": "ℹ", "WARN": "⚠", "ERROR": "⛔"}


def explain(level: str, message: str) -> tuple[str, str, bool]:
    """Повертає (заголовок, пояснення, чи_потрібна_дія_користувача)."""
    low = message.casefold()
    for needle, title, text, action in _RULES:
        if needle.casefold() in low:
            return title, text, action
    if level == "ERROR":
        return "Сталася помилка", "Скопіюйте запис кнопкою «Для підтримки» і надішліть розробнику.", False
    return message.split(";")[0][:90], "", False


def needs_action(message: str) -> bool:
    return explain("WARN", message)[2]


def icon(level: str) -> str:
    return _LEVEL_ICON.get(level, "ℹ")


def task_id_of(source: str | None) -> int | None:
    m = re.match(r"task#(\d+)", source or "")
    return int(m.group(1)) if m else None


def account_id_of(source: str | None) -> int | None:
    m = re.match(r"account#(\d+)", source or "")
    return int(m.group(1)) if m else None
